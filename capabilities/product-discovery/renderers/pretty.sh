#!/usr/bin/env bash

set -euo pipefail

jq -r '

################################################################################
# Header
################################################################################

"MCU Products",
"============",
"",

################################################################################
# Installed
################################################################################

"Installed",
"---------",

(
    .products[]
    | select(.registered == true)
    | "✓ \(.name)"
),

"",

################################################################################
# Available
################################################################################

"Available",
"---------",

(
    .products[]
    | select(.registered == false)
    | "○ \(.name)"
)

'
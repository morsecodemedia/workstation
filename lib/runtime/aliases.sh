#!/usr/bin/env bash

################################################################################
# Runtime Aliases
################################################################################

runtime_aliases_initialize() {

    ############################################################################
    # Shell
    ############################################################################

    alias mkdir='mkdir -p'
    alias grep='grep --color=auto'

    ############################################################################
    # Directory Navigation
    ############################################################################

    alias ll='ls -lha'
    alias lsd='ls -Gl | grep "^d"'

    alias cd..='cd ..'
    alias ..='cd ..'
    alias ...='cd ../..'
    alias ....='cd ../../..'
    alias .....='cd ../../../..'
    alias ......='cd ../../../../..'

    ############################################################################
    # Utilities
    ############################################################################

    alias dskill="find . -name '*.DS_Store' -type f -ls -delete"

}